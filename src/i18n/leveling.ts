export type LevelingKey = keyof (typeof ui)['en'];

export function levT(locale: Locale) {
  return (key: LevelingKey, vars: Record<string, string | number> = {}): string => {
    const table = ui[locale] as Partial<Record<LevelingKey, string>>;
    let text = table[key] ?? ui[defaultLocale][key];
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };
}
