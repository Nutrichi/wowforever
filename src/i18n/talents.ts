export type TalentUiKey = keyof (typeof ui)['en'];

/** Vertaalt een tekst van TALENTS en vult {sleutels} in. Ontbreekt iets, dan Engels. */
export function talT(locale: Locale) {
  return (key: TalentUiKey, vars: Record<string, string | number> = {}): string => {
    const table = ui[locale] as Partial<Record<TalentUiKey, string>>;
    let text = table[key] ?? ui[defaultLocale][key];
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };
}
