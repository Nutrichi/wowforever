export type PickerKey = keyof (typeof words)['en'];

export function pickT(locale: Locale) {
  return (key: PickerKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, String(v)), words[locale][key] ?? words.en[key]);
}
