export type TsKey = keyof (typeof words)['en'];

export function tsT(locale: Locale) {
  return (key: TsKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, String(v)), words[locale][key] ?? words.en[key]);
}

