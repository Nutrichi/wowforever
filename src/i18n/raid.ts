export type RaidKey = keyof (typeof ui)['en'];

export function raidT(locale: Locale) {
  return (key: RaidKey, vars: Record<string, string | number> = {}): string => {
    const table = ui[locale] as Partial<Record<RaidKey, string>>;
    let text = table[key] ?? ui[defaultLocale][key];
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };
}

/** Alle teksten van één taal, voor het script in de browser. */
export function raidStrings(locale: Locale): Record<RaidKey, string> {
  return { ...ui[defaultLocale], ...ui[locale] };
}
