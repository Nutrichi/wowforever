type DungeonKey = keyof typeof words.en;

export function dungeonT(locale: Locale) {
  return (key: DungeonKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce((text, [k, v]) => text.replaceAll(`{${k}}`, String(v)), words[locale][key] ?? words.en[key]);
}
